"""ตรวจ Distress Message ภาษาไทยในเครื่อง (ทำงานได้แม้ Offline)

ระดับเรียงจากรุนแรงที่สุด: self_harm (ทำร้ายตนเอง) → quit (ไม่อยากเรียนต่อ) → stress (เครียด ท้อ)
ตรวจด้วยรายการคำก่อนเสมอ ตอนออนไลน์ LLM ยังส่งรหัส TRIGGER_CIRCUIT_BREAKER เสริมได้อีกชั้น
"""

import re

SELF_HARM = [
    "อยากตาย", "ไม่อยากมีชีวิต", "ฆ่าตัวตาย", "ทำร้ายตัวเอง", "ทำร้ายตนเอง", "กรีดแขน", "กรีดข้อมือ",
    "จบชีวิต", "ไม่อยากอยู่บนโลก", "ตายไปซะ", "ไม่อยากตื่น", "อยากหายไปจากโลก",
]
QUIT = [
    "ไม่อยากเรียนแล้ว", "ไม่อยากเรียนต่อ", "ไม่อยากเรียน", "เลิกเรียน", "ไม่เอาแล้ว", "ขอเลิก",
    "ไม่ทำแล้ว", "ไม่อยากทำแล้ว", "ยอมแพ้",
]
# ใช้คำเต็มแทนคำสั้นที่อาจซ้อนอยู่ในคำอื่น เช่น "ท้อ" อยู่ใน "ปวดท้อง"
STRESS = [
    "เครียด", "ท้อแท้", "ท้อใจ", "รู้สึกท้อ", "ท้อมาก", "ท้อแล้ว", "หมดไฟ", "เหนื่อยมาก", "ไม่ไหว",
    "ร้องไห้", "ทำไม่ได้สักที", "ทำไม่ได้เลย", "ฉันโง่", "ผมโง่", "หนูโง่", "เราโง่", "ห่วยแตก",
    "เบื่อมาก", "กดดัน", "หงุดหงิด", "สิ้นหวัง", "ไม่มีทางทำได้",
]

LEVELS = [("self_harm", SELF_HARM), ("quit", QUIT), ("stress", STRESS)]


def _normalize(text: str) -> str:
    text = re.sub(r"[\s​‌‍]+", "", text or "").lower()
    # ลดตัวอักษรที่พิมพ์ซ้ำ เช่น "เครียดดดด" → "เครียด"
    return re.sub(r"(.)\1{2,}", r"\1", text)


def detect(text: str) -> dict:
    norm = _normalize(text)
    for level, words in LEVELS:
        for word in words:
            if _normalize(word) in norm:
                return {"level": level, "matched": word}
    return {"level": None, "matched": None}
